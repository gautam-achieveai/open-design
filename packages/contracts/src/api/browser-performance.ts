import type { McpApprovalView } from './mcp-approval.js';

/** Sanitized, derived browser evidence. Raw traces and page content are never reports. */
export const BROWSER_PERFORMANCE_SCHEMA_VERSION = 1 as const;
export const BROWSER_PERFORMANCE_MAX_REPORT_BYTES = 1_048_576;
export type BrowserPerformanceCompleteness = 'complete' | 'partial' | 'failed';
export interface BrowserPerformanceOverrideRequest { reportId: string; cpu: number; tabId?: string; approvalRequestId?: string }
export type BrowserPerformanceOverrideResponse =
  | { status: 'approval_required'; approvalRequestId: string; approval: McpApprovalView }
  | { status: 'applied'; reportId: string; cpu: number };
export type BrowserPerformanceEvidenceKind = 'task' | 'sample' | 'input' | 'request' | 'lcp' | 'layout-shift' | 'paint' | 'frame' | 'style';

export interface BrowserPerformanceSourceReference {
  /** Generated opaque label; never a raw URL, selector or function name. */
  label: string;
  line?: number;
  column?: number;
  mapping: 'generated' | 'project-local' | 'unavailable';
  /** Added only after daemon verifies the generated file is in the authorized project. */
  generated?: { path: string; line: number; column: number; functionName?: string };
  original?: { path: string; line: number; column: number };
  /** Local source may have changed since the page loaded; no captured-script hash was verified. */
  resolutionBasis?: 'current-project-files-unverified-at-capture';
  unavailableReason?: 'source-unavailable' | 'external-source' | 'invalid-source-path' | 'source-too-large' | 'map-missing' | 'map-invalid' | 'map-external' | 'map-too-large' | 'map-unmapped' | 'source-outside-project';
}

/** Ephemeral host-to-daemon lookup input. Never saved or returned by public report APIs. */
export interface BrowserPerformanceSourceLocator {
  label: string;
  /** No credentials, query or fragment. Resolver must still authorize origin and path. */
  url: string;
  /** One-based generated location. */
  line: number;
  column: number;
  /** Strict identifier/member token, persisted only after verification against local source. */
  functionName?: string;
  kind?: 'script' | 'stylesheet';
}

export interface BrowserPerformanceEvidence {
  id: string;
  kind: BrowserPerformanceEvidenceKind;
  /** Relative to the clock identified by clock. */
  atMs: number;
  durationMs?: number;
  clock: 'trace' | 'document' | 'profile' | 'network';
  /** Null when a capture spans documents and this observation cannot be attributed safely. */
  documentId: string | null;
  values: Record<string, number | boolean | null>;
  relatedIds?: string[];
  sources?: BrowserPerformanceSourceReference[];
  request?: { resourceType: 'Document' | 'Stylesheet' | 'Image' | 'Media' | 'Font' | 'Script' | 'XHR' | 'Fetch' | 'Other'; initiatorType: 'parser' | 'script' | 'preload' | 'preflight' | 'other'; observation?: 'cdp' | 'resource-timing' };
  target?: { label: string; backendNodeId?: number };
}

export interface BrowserPerformanceFinding {
  id: string;
  kind: BrowserPerformanceEvidenceKind | 'coverage';
  severity: 'info' | 'warning';
  /** Fixed diagnostic text generated by the analyzer, never page content. */
  title: string;
  interpretation: 'observed' | 'hypothesis';
  evidenceIds: string[];
}

export interface BrowserPerformanceCoverage {
  traceComplete: boolean;
  observerAvailable: boolean;
  retainedEvents: number;
  /** Valid completed main-thread tasks, including tasks below the long-task threshold. */
  rendererTasks: number;
  droppedEvents: number;
  retainedBytes: number;
  omittedEvidence: number;
  /** Stable diagnostic codes, not raw exception messages. */
  reasons: string[];
  cpuSampling?: { status: 'captured' | 'unavailable' | 'disabled'; intervalUs: number; retainedSamples: number; droppedSamples: number };
  inputTiming?: { supported: boolean; retained: number; dropped: number };
  load?: { preNavigation: boolean; retainedRequests: number; droppedRequests: number; documents: number; lcpSupported: boolean };
  rendering?: { supported: boolean; retainedShifts: number; retainedPaints: number; retainedFrames: number; cssTargets: number; displayRefreshHz: null };
}

export interface BrowserPerformanceEnvironment {
  browserVersion: string;
  viewport: { width: number; height: number; deviceScaleFactor: number } | null;
  visible: boolean;
  cpuThrottle: number;
  network: string;
  cacheDisabled: boolean;
  reducedMotion: boolean | null;
  animationRate: number;
  /** Identifies the document observed at capture start without exposing its URL. */
  documentId: string;
  timeOriginMs: number | null;
  traceOriginUs?: number;
  profileOriginUs?: number;
  networkOriginUs?: number;
  overridesFingerprint?: string;
  appliedCpuThrottle?: number;
}

export type BrowserPerformanceRestoration =
  | { status: 'not-modified-by-capture'; settingsChangedDuringCapture: boolean }
  | { status: 'restored' | 'failed' | 'conflict'; priorCpu: number; appliedCpu: number; restoredCpu: number | null; settingsChangedDuringCapture: boolean; reason?: 'cpu-changed-externally' | 'apply-timeout' | 'restore-failed' };

export interface BrowserPerformanceDocument {
  documentId: string;
  timeOriginMs: number;
  observerStartedAtMs: number;
  observedBeforeLoad: boolean;
}

export interface BrowserPerformanceReport {
  schemaVersion: typeof BROWSER_PERFORMANCE_SCHEMA_VERSION;
  reportId: string;
  scenarioId?: string;
  startedAt: string;
  durationMs: number;
  completeness: BrowserPerformanceCompleteness;
  summary: string;
  environment: BrowserPerformanceEnvironment;
  coverage: BrowserPerformanceCoverage;
  findings: BrowserPerformanceFinding[];
  evidence: BrowserPerformanceEvidence[];
  documents?: BrowserPerformanceDocument[];
  restoration?: BrowserPerformanceRestoration;
}

export interface BrowserPerformanceReportSummary {
  schemaVersion: typeof BROWSER_PERFORMANCE_SCHEMA_VERSION;
  reportId: string;
  scenarioId?: string;
  startedAt: string;
  durationMs: number;
  completeness: BrowserPerformanceCompleteness;
  summary: string;
  findingsCount: number;
  evidenceCount: number;
}

export interface BrowserPerformancePage {
  reportId: string;
  schemaVersion: typeof BROWSER_PERFORMANCE_SCHEMA_VERSION;
  section: 'findings' | 'evidence';
  items: BrowserPerformanceFinding[] | BrowserPerformanceEvidence[];
  total: number;
  nextCursor: string | null;
  omitted: number;
  completeness: BrowserPerformanceCompleteness;
}

export interface BrowserPerformanceCaptureStart {
  recording: true;
  reportId: string;
  maxMs: number;
  visible: boolean;
}

/** Added to the legacy render-stop result; only this property is persisted. */
export interface BrowserPerformanceCaptureResult {
  performanceReport: BrowserPerformanceReport;
  performanceSources?: BrowserPerformanceSourceLocator[];
}

export interface BrowserPerformanceStatus {
  state: 'idle' | 'pending';
  capture: { tabId: string; reportId: string | null; maxMs: number } | null;
}

export interface BrowserPerformanceReportList {
  items: BrowserPerformanceReportSummary[];
  total: number;
  nextCursor: string | null;
}

/** Durable report metadata; evidence and findings are retrieved through pages. */
export interface BrowserPerformanceReportDetail extends BrowserPerformanceReportSummary {
  tabId: string;
  expiresAt: string;
  environment: BrowserPerformanceEnvironment;
  coverage: BrowserPerformanceCoverage;
  retention: { days: number; maxReportBytes: number; totalBytes: number };
  documents?: BrowserPerformanceDocument[];
  restoration?: BrowserPerformanceReport['restoration'];
}

export interface BrowserPerformanceComparisonRequest {
  baselineReportIds: string[];
  candidateReportIds: string[];
}

export interface BrowserPerformanceMetricDistribution {
  samples: number[];
  min: number;
  median: number;
  max: number;
  mean: number;
  stddev: number;
}

export type BrowserPerformanceComparisonWarning = 'scenario-missing' | 'scenario-mismatch' | 'environment-mismatch' | 'environment-incomplete' | 'target-changed' | 'capture-incomplete' | 'duration-differs' | 'metric-unavailable' | 'override-not-restored' | 'settings-changed-during-capture';

export interface BrowserPerformanceComparison {
  schemaVersion: 1;
  comparable: boolean;
  scenarioId: string | null;
  baselineReportIds: string[];
  candidateReportIds: string[];
  warnings: BrowserPerformanceComparisonWarning[];
  metrics: Array<{
    metric: 'longTaskMaxMs' | 'longTaskTotalMs' | 'inputMaxMs' | 'lcpMs' | 'cls';
    unit: 'ms' | 'score';
    baseline: BrowserPerformanceMetricDistribution;
    candidate: BrowserPerformanceMetricDistribution;
    medianDelta: number;
    medianDeltaPercent: number | null;
  }>;
}
